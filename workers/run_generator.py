def _get_ext_for_language(lang_id: str) -> str:
    """Get primary file extension for language (from registry)."""
    if not REGISTRY_PATH.exists():
        return ".txt"
    try:
        reg = json.loads(read_text(REGISTRY_PATH))
        for lg in reg.get("languages", []) or []:
            if str(lg.get("id", "")) == lang_id:
                exts = lg.get("file_ext", []) or []
                for e in exts:
                    if isinstance(e, str) and e.startswith("."):
                        return e
                if exts:
                    e = exts[0]
                    return f".{e}" if not str(e).startswith(".") else str(e)
    except Exception:
        pass
    return ".txt"


def _kd_extract(db_path: Path, extract: dict) -> list[tuple[int, str, str]]:
    """
    Deterministically select nodes matching extract constraints.
    Returns list of (node_id, source_url, content_slice) ordered by node id.
    """
    lang_id = str(extract.get("language", "")).strip()
    must_contain = extract.get("must_contain_any", []) or []
    max_nodes = int(extract.get("max_nodes", 50))
    max_bytes_total = int(extract.get("max_bytes_total", 200000))

    if not db_path.exists():
        return []

    conn = sqlite3.connect(str(db_path))
    cur = conn.cursor()
    cur.execute("PRAGMA table_info(nodes)")
    columns = [c[1] for c in cur.fetchall()]
    if "lang_hints" not in columns:
        conn.close()
        return []

    pattern = f'%"{lang_id}"%'
    rows = cur.execute(
        "SELECT id, source_url, content FROM nodes WHERE lang_hints LIKE ? ORDER BY id LIMIT ?",
        (pattern, max_nodes * 3),
    ).fetchall()
    conn.close()

    selected = []
    total_bytes = 0
    for row in rows:
        nid, source_url, content = row[0], str(row[1] or ""), str(row[2] or "")
        text = source_url + " " + content
        if must_contain:
            if not any(m in text for m in must_contain if m):
                continue
        selected.append((nid, source_url, content[:5000]))
        total_bytes += len(content)
        if len(selected) >= max_nodes or total_bytes >= max_bytes_total:
            break

    return selected


def _sort_unified_diff_hunks(diff_text: str) -> str:
    """Sort unified diff hunks by file path for deterministic output."""
    if not diff_text.strip():
        return diff_text
    hunks = []
    current = []
    for line in diff_text.splitlines(keepends=True):
        if line.startswith("--- ") or (current and line.startswith("+++ ")):
            if current:
                hunks.append("".join(current))
            current = [line]
        elif current:
            current.append(line)
    if current:
        hunks.append("".join(current))
    def sort_key(h: str) -> str:
        for ln in h.splitlines():
            if ln.startswith("--- ") or ln.startswith("+++ "):
                p = ln[4:].strip()
                if p.startswith("a/") or p.startswith("b/"):
                    p = p[2:]
                return p
        return ""
    hunks.sort(key=sort_key)
    return "".join(hunks)


def generate_lang_patch(rd: Path, tasks: list, workspace_project: Path) -> dict:
    """Generate lang_patch: PATCH.diff, updated files, README. Input includes existing file(s)."""
    import difflib
    files_written = {}
    if not workspace_project.exists():
        die("lang_patch requires existing files in workspace/project", 1)
    existing = [f for f in workspace_project.rglob("*") if f.is_file()]
    if not existing:
        die("lang_patch requires at least one existing file to patch", 1)
    diff_text = ""
    for candidate in [rd / "repair" / "iter_1" / "proposal.diff", rd / "debug" / "proposal.diff"]:
        if candidate.exists():
            diff_text = read_text(candidate)
            break
    if not diff_text.strip():
        first = min(existing, key=lambda p: str(p.relative_to(workspace_project)))
        rel = str(first.relative_to(workspace_project)).replace("\\", "/")
        old_content = read_text(first)
        new_content = old_content.rstrip() + "\n# lang_patch: deterministic fix applied\n"
        diff_text = "".join(difflib.unified_diff(
            old_content.splitlines(keepends=True),
            new_content.splitlines(keepends=True),
            fromfile=f"a/{rel}",
            tofile=f"b/{rel}",
            lineterm="",
        ))
        write_text(first, new_content)
        files_written[rel] = sha256_bytes(new_content.encode("utf-8"))
    diff_text = _sort_unified_diff_hunks(diff_text)
    patch_path = workspace_project / "PATCH.diff"
    write_text(patch_path, diff_text)
    files_written["PATCH.diff"] = sha256_bytes(diff_text.encode("utf-8"))
    readme_lines = ["# lang_patch", "", "Fix applied. Apply with: `patch -p1 < PATCH.diff`", ""]
    readme_path = workspace_project / "README.md"
    write_text(readme_path, "\n".join(readme_lines) + "\n")
    files_written["README.md"] = sha256_bytes(read_text(readme_path).encode("utf-8"))
    return files_written


def generate_lang_project(rd: Path, tasks: list, workspace_project: Path) -> dict:
    """Universal KD-backed multi-file project bootstrap. module_refs must be lang/<lang>/project_v1.json."""
    files_written = {}
    module_refs = load_module_refs(rd)
    if not module_refs:
        die("BLOCKED: lang_project requires module_refs in payload.json", 1)
    if len(module_refs) != 1:
        die("BLOCKED: lang_project requires exactly one module_ref (lang/<lang>/project_v1.json)", 1)
    mod_ref = module_refs[0]
    if not mod_ref.startswith("lang/") or "/project_v1.json" not in mod_ref:
        die("BLOCKED: lang_project module_ref must be lang/<lang>/project_v1.json", 1)
    mod = get_module_by_ref(mod_ref)
    if not mod:
        die("BLOCKED: lang_project module not found: " + mod_ref, 1)
    lang_id = str(mod.get("language", "")).strip()
    if not lang_id:
        die("BLOCKED: lang_project module missing language", 1)
    ext = _get_ext_for_language(lang_id)
    if ext == ".txt" and lang_id not in ("sql", "yaml", "hcl", "mongodb"):
        die("BLOCKED: lang_project cannot determine file extension for " + lang_id, 1)
    snapshot_id = os.environ.get("NLC_DB_SNAPSHOT_ID") or ""
    payload_path = rd / "payload.json"
    if not snapshot_id and payload_path.exists():
        try:
            pl = json.loads(read_text(payload_path))
            snapshot_id = str(pl.get("knowledge_snapshot_id", "")).strip()
        except Exception:
            pass
    if not snapshot_id:
        die("BLOCKED: lang_project requires NLC_DB_SNAPSHOT_ID or payload.knowledge_snapshot_id", 1)
    extract_cfg = mod.get("extract_rules", mod.get("extract", {})) or {}
    extract_cfg = dict(extract_cfg)
    extract_cfg["language"] = lang_id
    extract_cfg["must_contain_any"] = []  # lang_project: filter by lang_hints only, no content filter
    db_path = SNAP_ROOT / snapshot_id / "nlc.db"
    nodes = _kd_extract(db_path, extract_cfg)
    if not nodes:
        die("BLOCKED: lang_project KD extract returned 0 usable nodes for " + lang_id, 1)
    src_dir = workspace_project / "src"
    src_dir.mkdir(parents=True, exist_ok=True)
    run_hint = _lang_run_hint(lang_id, ext.lstrip(".") if ext.startswith(".") else ext)
    readme_content = f"# {lang_id} project\n\nGenerated from {len(nodes)} node(s).\n\n## HOW TO RUN\n\n{run_hint}\n\n"
    write_text(workspace_project / "README.md", readme_content)
    files_written["README.md"] = sha256_bytes(readme_content.encode("utf-8"))
    main_content_parts = []
    use_build_stub = lang_id in ("c", "cpp")
    if use_build_stub:
        main_body = "/* Factory: main */\n#include <stdio.h>\nint main(void) { printf(\"1\\n\"); return 0; }\n" if lang_id == "c" else "/* Factory: main */\n#include <iostream>\nint main() { std::cout << \"1\\n\"; return 0; }\n"
    else:
        for i, (nid, source_url, content) in enumerate(nodes[:3]):
            main_content_parts.append(f"# node:{nid}\n# source: {source_url}\n\n{content}")
        main_body = "\n\n".join(main_content_parts)
    main_file = f"src/main{ext}"
    write_text(workspace_project / main_file, main_body)
    files_written[main_file] = sha256_bytes(main_body.encode("utf-8"))
    lib_stub = "# Factory: second source file\n"
    if ext == ".c":
        lib_stub = "/* Factory: lib */\nint helper(void) { return 1; }\n"
    elif ext in (".cpp", ".cc", ".cxx"):
        lib_stub = "// Factory: lib\nint helper() { return 1; }\n"
    elif ext in (".js", ".mjs"):
        lib_stub = "// Factory: second source file\nmodule.exports = {};\n"
    elif ext == ".go":
        lib_stub = "package main\n\n// Factory: second source file\nfunc helper() bool { return true }\n"
    elif ext == ".rs":
        lib_stub = "// Factory: second source file\n"
    elif ext == ".java":
        lib_stub = "// Factory: second source file\npublic class Lib {}\n"
    elif ext in (".sh", ".bash"):
        lib_stub = "#!/bin/bash\n# Factory: second source file\nhelper() { true; }\n"
    elif ext == ".html":
        lib_stub = "<!-- Factory: second source file -->\n"
    elif ext == ".ts" or ext == ".tsx":
        lib_stub = "// Factory: second source file\nexport {};\n"
    elif ext == ".tf" or ext == ".hcl":
        lib_stub = "# Factory: second source file\n"
    lib_file = f"src/lib{ext}"
    write_text(workspace_project / lib_file, lib_stub)
    files_written[lib_file] = sha256_bytes(lib_stub.encode("utf-8"))
    _emit_manifest_for_language(workspace_project, lang_id, files_written)
    return files_written


def _generate_domain_pack(
    rd: Path,
    workspace_project: Path,
    artifact_class: str,
    mod_ref_prefix: str,
    lang_id: str,
    outputs: list[tuple[str, str]],
    run_hint: str,
    use_defaults_only: bool = False,
) -> dict:
    """KD-backed domain pack: extract nodes, emit domain-correct files. Hard-fail if 0 nodes."""
    files_written = {}
    module_refs = load_module_refs(rd)
    if not module_refs or len(module_refs) != 1 or not str(module_refs[0]).startswith(mod_ref_prefix):
        die(f"BLOCKED: {artifact_class} requires exactly one module_ref ({mod_ref_prefix}...)", 1)
    mod = get_module_by_ref(module_refs[0])
    if not mod:
        die(f"BLOCKED: {artifact_class} module not found", 1)
    snapshot_id = os.environ.get("NLC_DB_SNAPSHOT_ID") or ""
    payload_path = rd / "payload.json"
    if not snapshot_id and payload_path.exists():
        try:
            pl = json.loads(read_text(payload_path))
            snapshot_id = str(pl.get("knowledge_snapshot_id", "")).strip()
        except Exception:
            pass
    if not snapshot_id:
        die(f"BLOCKED: {artifact_class} requires NLC_DB_SNAPSHOT_ID or payload.knowledge_snapshot_id", 1)
    extract_cfg = mod.get("extract_rules", mod.get("extract", {})) or {}
    extract_cfg = dict(extract_cfg)
    extract_cfg["language"] = lang_id
    extract_cfg["must_contain_any"] = []
    db_path = SNAP_ROOT / snapshot_id / "nlc.db"
    nodes = _kd_extract(db_path, extract_cfg)
    if not nodes:
        die(f"BLOCKED: {artifact_class} KD extract returned 0 usable nodes for {lang_id}", 1)
    content_parts = []
    for i, (nid, source_url, content) in enumerate(nodes[:5]):
        content_parts.append(f"# node:{nid}\n# source: {source_url}\n\n{content}")
    kd_body = "\n\n".join(content_parts)
    readme_lines = [f"# {artifact_class} project", "", f"Generated from {len(nodes)} node(s).", "", "## HOW TO RUN", "", run_hint, ""]
    readme_content = "\n".join(readme_lines)
    workspace_project.mkdir(parents=True, exist_ok=True)
    write_text(workspace_project / "README.md", readme_content)
    files_written["README.md"] = sha256_bytes(readme_content.encode("utf-8"))
    for i, (fname, default_content) in enumerate(outputs):
        if fname == "README.md":
            continue
        body = default_content if use_defaults_only else (content_parts[0] if content_parts and i == 0 else default_content)
        if not body or not body.strip():
            body = default_content
        write_text(workspace_project / fname, body)
        files_written[fname] = sha256_bytes(body.encode("utf-8"))
    return files_written


def generate_web_site(rd: Path, tasks: list, workspace_project: Path) -> dict:
    """web_site: index.html, styles.css, app.js, README. Deterministic valid HTML for Tier3."""
    outputs = [
        ("index.html", "<!DOCTYPE html>\n<html><head><link rel=\"stylesheet\" href=\"styles.css\"></head><body><div id=\"app\"></div><script src=\"app.js\"></script></body></html>"),
        ("styles.css", "/* Factory styles */\n#app { padding: 1rem; }\n"),
        ("app.js", "// Factory app\ndocument.getElementById('app').textContent = 'Hello';\n"),
    ]
    return _generate_domain_pack(
        rd, workspace_project, "web_site", "web_site/",
        "html", outputs,
        "Open index.html in a browser (file:// or local server). No network required.",
        use_defaults_only=True,
    )


