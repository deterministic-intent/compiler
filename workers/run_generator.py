REGISTRY_PATH = BASE / "nlc" / "languages" / "registry.json"
MARKERS_PATH = BASE / "nlc" / "languages" / "language_markers.json"


def _required_manifests_for_language(lang_id: str) -> list[str]:
    if not MARKERS_PATH.exists():
        return []
    try:
        markers = json.loads(read_text(MARKERS_PATH))
        return markers.get("required_manifests_by_language", {}).get(lang_id, [])
    except Exception:
        return []


def _emit_manifest_for_language(workspace_project: Path, lang_id: str, files_written: dict) -> None:
    """Emit required build manifest for language (factory enforcement)."""
    required = _required_manifests_for_language(lang_id)
    if not required:
        return
    manifest_content = ""
    manifest_name = ""
    if lang_id == "python" and "requirements.txt" in required:
        manifest_name = "requirements.txt"
        manifest_content = "# Factory manifest (pinned)\nrequests==2.31.0\n"
    elif lang_id == "python" and "pyproject.toml" in required:
        manifest_name = "pyproject.toml"
        manifest_content = '[project]\nname = "app"\nversion = "0.1.0"\ndependencies = ["requests==2.31.0"]\n'
    elif lang_id == "javascript":
        manifest_name = "package.json"
        manifest_content = '{"name":"app","version":"0.1.0","main":"src/main.js"}\n'
        p = workspace_project / manifest_name
        write_text(p, manifest_content)
        files_written[manifest_name] = sha256_bytes(manifest_content.encode("utf-8"))
        lock_content = '{"name":"app","version":"0.1.0","lockfileVersion":3,"packages":{"":{"name":"app","version":"0.1.0"}}}\n'
        write_text(workspace_project / "package-lock.json", lock_content)
        files_written["package-lock.json"] = sha256_bytes(lock_content.encode("utf-8"))
        return
    elif lang_id == "typescript":
        manifest_name = "package.json"
        manifest_content = '{"name":"app","version":"0.1.0","main":"src/main.js"}\n'
        p = workspace_project / manifest_name
        write_text(p, manifest_content)
        files_written[manifest_name] = sha256_bytes(manifest_content.encode("utf-8"))
        lock_content = '{"name":"app","version":"0.1.0","lockfileVersion":3,"packages":{"":{"name":"app","version":"0.1.0"}}}\n'
        write_text(workspace_project / "package-lock.json", lock_content)
        files_written["package-lock.json"] = sha256_bytes(lock_content.encode("utf-8"))
        manifest_name = "tsconfig.json"
        manifest_content = '{"compilerOptions":{"target":"ES2020","module":"commonjs","strict":true},"include":["src/**/*"]}\n'
    elif lang_id == "rust":
        manifest_name = "Cargo.toml"
        manifest_content = '[package]\nname = "app"\nversion = "0.1.0"\nedition = "2021"\n'
        p = workspace_project / manifest_name
        write_text(p, manifest_content)
        files_written[manifest_name] = sha256_bytes(manifest_content.encode("utf-8"))
        lock_content = '# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = "app"\nversion = "0.1.0"\ndependencies = []\n\n'
        write_text(workspace_project / "Cargo.lock", lock_content)
        files_written["Cargo.lock"] = sha256_bytes(lock_content.encode("utf-8"))
        return
    elif lang_id == "go":
        manifest_name = "go.mod"
        manifest_content = "module app\n\ngo 1.21\n"
        p = workspace_project / manifest_name
        write_text(p, manifest_content)
        files_written[manifest_name] = sha256_bytes(manifest_content.encode("utf-8"))
        write_text(workspace_project / "go.sum", "")
        files_written["go.sum"] = sha256_bytes(b"")
        return
    elif lang_id == "java" and ("pom.xml" in required or "build.gradle" in required):
        manifest_name = "pom.xml"
        manifest_content = '<?xml version="1.0"?>\n<project><modelVersion>4.0.0</modelVersion><groupId>app</groupId><artifactId>app</artifactId><version>0.1.0</version></project>\n'
    elif lang_id == "csharp" and "*.csproj" in required:
        manifest_name = "app.csproj"
        manifest_content = '<Project><PropertyGroup><OutputType>Exe</OutputType></PropertyGroup></Project>\n'
    elif lang_id == "kotlin" and "build.gradle" in required:
        manifest_name = "build.gradle"
        manifest_content = 'plugins { id("java") }\n'
    elif lang_id == "php" and "composer.json" in required:
        manifest_name = "composer.json"
        manifest_content = '{"name":"app/app","require":{}}\n'
    elif lang_id == "ruby" and "Gemfile" in required:
        manifest_name = "Gemfile"
        manifest_content = 'source "https://rubygems.org"\n'
    if manifest_name and manifest_content:
        p = workspace_project / manifest_name
        write_text(p, manifest_content)
        files_written[manifest_name] = sha256_bytes(manifest_content.encode("utf-8"))


def die(msg: str, code: int = 2):
    print(f"ERROR: {msg}", file=sys.stderr, flush=True)
    raise SystemExit(code)

def sha256_bytes(b: bytes) -> str:
    h = hashlib.sha256()
    h.update(b)
    return h.hexdigest()

def read_text(p: Path) -> str:
    if not p.exists():
        return ""
    return p.read_text(encoding="utf-8", errors="replace")

def write_text(p: Path, s: str) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(s, encoding="utf-8")

def load_artifact_class(rd: Path) -> tuple[str, dict]:
    """Load artifact class from payload.json"""
    payload_path = rd / "payload.json"
    if not payload_path.exists():
        return "python_cli", {}
    
    try:
        payload = json.loads(read_text(payload_path))
        artifact_class = payload.get("artifact_class", "python_cli")
        artifact_def = payload.get("artifact_class_definition", {})
        return artifact_class, artifact_def
    except Exception:
        return "python_cli", {}

def load_tasks(rd: Path) -> list:
    """Load tasks from TASKS.json"""
    tasks_path = rd / "TASKS.json"
    if not tasks_path.exists():
        return []
    
    try:
        tasks_obj = json.loads(read_text(tasks_path))
        return tasks_obj.get("tasks", [])
    except Exception:
        return []

def get_module(artifact_class: str, module_name: str) -> dict:
    """Load a module from the module library"""
    module_path = MODULES_DIR / artifact_class / f"{module_name}.json"
    if not module_path.exists():
        return {}
    
    try:
        return json.loads(read_text(module_path))
    except Exception:
        return {}

def load_module_refs(request_dir: Path) -> list[str]:
    """Load module_refs from payload.json (intent-driven execution)."""
    payload_path = request_dir / "payload.json"
    if not payload_path.exists():
        return []
    
    try:
        payload = json.loads(read_text(payload_path))
        module_refs = payload.get("module_refs", [])
        if isinstance(module_refs, list):
            return [str(ref).strip() for ref in module_refs if str(ref).strip()]
    except Exception:
        pass
    
    return []

def get_module_by_ref(module_ref: str) -> dict:
    """Load a module by its reference path (e.g., 'python_cli/argparse_setup.json')."""
    parts = module_ref.split("/", 1)
    if len(parts) != 2:
        return {}
    
    artifact_class, module_file = parts
    module_path = MODULES_DIR / artifact_class / module_file
    if not module_path.exists():
        return {}
    
    try:
        return json.loads(read_text(module_path))
    except Exception:
        return {}

